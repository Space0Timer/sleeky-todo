/*
 * Generates a declaration file beside every *.module.scss so that a class name
 * is checked rather than assumed.
 *
 * Without this, Vite's own `declare module '*.module.scss'` types every module
 * as an index signature, so `styles.todoCrad` compiles, renders `class=""`, and
 * the element silently loses its styling. The generated declarations resolve
 * ahead of that wildcard and turn the same typo into a build failure.
 *
 * TypeScript finds them through `allowArbitraryExtensions`: an import of
 * `./X.module.scss` resolves to `./X.module.d.scss.ts`.
 *
 * The output is generated, so it is git-ignored and regenerated by `yarn dev`,
 * `yarn build`, and CI before anything type-checks.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

import postcss from 'postcss'
import * as sass from 'sass'

const projectRoot = fileURLToPath(new URL('..', import.meta.url))
const sourceRoot = join(projectRoot, 'src')

/**
 * @param {string} directory
 * @returns {Generator<string>}
 */
function* findModules(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)

    if (entry.isDirectory()) yield* findModules(path)
    else if (entry.name.endsWith('.module.scss')) yield path
  }
}

/**
 * Matches a class in a selector. Attribute values and pseudo-classes carry no
 * leading dot, so they cannot be mistaken for one.
 */
const classPattern = /\.(-?[_a-zA-Z][\w-]*)/g

/**
 * Mirrors the `camelCaseOnly` conversion configured in vite.config.ts. That
 * setting removes the kebab-case key, so this is the only spelling a component
 * can use.
 *
 * @param {string} name
 * @returns {string}
 */
function toCamelCase(name) {
  return name.replace(/-+(\w)/g, (_, character) => String(character).toUpperCase())
}

/**
 * Compiles the module so that nesting, mixins, and media queries are resolved
 * first. Reading the source directly would miss a class that only a mixin or a
 * nested block introduces.
 *
 * @param {string} file
 * @returns {string[]}
 */
function classNamesOf(file) {
  const { css } = sass.compile(file, { loadPaths: [sourceRoot] })
  /** @type {Set<string>} */
  const names = new Set()

  postcss.parse(css).walkRules((rule) => {
    for (const match of rule.selector.matchAll(classPattern)) {
      names.add(toCamelCase(match[1]))
    }
  })

  return [...names].sort()
}

/**
 * @param {string[]} names
 * @returns {string}
 */
function declarationFor(names) {
  const body = names.length > 0
    ? names.map((name) => `  readonly ${name}: string`).join('\n')
    : '  readonly [name: string]: never'

  return `// Generated by scripts/generate-css-module-types.mjs. Do not edit.

declare const styles: {
${body}
}

export default styles
`
}

let written = 0

for (const file of findModules(sourceRoot)) {
  const target = file.replace(/\.module\.scss$/, '.module.d.scss.ts')
  const next = declarationFor(classNamesOf(file))

  // Only touch the file when it changes, so a watching type-checker is not
  // restarted on every run.
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    current = ''
  }

  if (current !== next) {
    writeFileSync(target, next)
    written += 1
  }
}

console.log(`CSS module types: ${written} file(s) written`)
